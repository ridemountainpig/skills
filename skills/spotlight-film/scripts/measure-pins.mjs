// Measures each shot's anchor on screen at its first and last frame and writes pins.js.
// Run after changing shot layouts, from the project root: node sf/measure-pins.mjs film [--mode object]
import { createRequire } from 'module';
import { createServer } from 'http';
import { readFile, writeFile } from 'fs/promises';
import { extname, join } from 'path';
const root = process.cwd();
const dir = process.argv[2] || 'film';   // the film folder, relative to the project root
// --mode object|light measures one anchor mode only (default: both, so ?anchor= can switch)
const mi = process.argv.indexOf('--mode'), modes = mi > 0 ? [process.argv[mi + 1]] : ['object', 'light'];
const { chromium } = createRequire(join(root, 'noop.js'))('playwright');
const types = { '.html': 'text/html', '.js': 'text/javascript', '.mjs': 'text/javascript', '.css': 'text/css', '.json': 'application/json', '.woff2': 'font/woff2', '.ttf': 'font/ttf' };
const server = createServer(async (req, res) => {
  try { const p = join(root, decodeURIComponent(req.url.split('?')[0])); const body = await readFile(p); res.writeHead(200, { 'content-type': types[extname(p)] || 'application/octet-stream' }); res.end(body); }
  catch { res.writeHead(404); res.end(); }
}).listen(0);
const port = server.address().port;
const browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const out = {};
for (const mode of modes) {
  const page = await browser.newPage({ viewport: { width: 1920, height: 1080 } });
  await page.goto(`http://localhost:${port}/${dir}/film.html?anchor=${mode}&nomatch`);
  await page.waitForFunction(() => window.__ready === true, null, { timeout: 60000 });
  const shots = await page.evaluate(() => window.__film.shots);
  out[mode] = {};
  for (const s of shots) {
    const r = {};
    for (const [k, t] of [['start', s.start + 0.001], ['end', s.end - 0.02]]) {
      await page.evaluate((t) => window.renderFrame(t), t);
      r[k] = await page.evaluate(() => {
        const a = window.__anchor; if (!a) return null;
        const st = document.getElementById('stage').getBoundingClientRect();
        let x0 = 1e9, y0 = 1e9, x1 = -1e9, y1 = -1e9;
        for (const rootEl of [a.root]) {
          if (getComputedStyle(rootEl).display === 'none') continue;
          for (const n of [rootEl, ...rootEl.querySelectorAll('*')]) {
            const b = n.getBoundingClientRect();
            if (b.width < 1 || b.height < 1 || getComputedStyle(n).display === 'none') continue;
            x0 = Math.min(x0, b.left); y0 = Math.min(y0, b.top); x1 = Math.max(x1, b.right); y1 = Math.max(y1, b.bottom);
          }
        }
        if (x1 < x0) return null;
        return { x: Math.round((x0 + x1) / 2 - st.left - 960), y: Math.round((y0 + y1) / 2 - st.top - 540), w: Math.round(Math.max(x1 - x0, 1)) };
      });
    }
    if (r.start || r.end) out[mode][s.id] = r;
  }
  await page.close();
}
await browser.close(); server.close();
await writeFile(join(root, dir, 'pins.js'), `// Generated by measure-pins.mjs: each shot's anchor on screen at its first and last frame.\nexport const PINS = ${JSON.stringify(out, null, 2)};\n`);
console.log(JSON.stringify(out));
